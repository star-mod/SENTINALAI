import argparse
import os
import random
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path

import requests
from dotenv import load_dotenv

load_dotenv(Path(__file__).resolve().parents[1] / ".env")


TYPES = ("physical_altercation", "fall_collapse", "abnormal_crowd_movement")
CAMERAS = {
    "cam_01": ("Central Plaza - North", {"lat": 12.9716, "lng": 77.5946, "label": "Central Plaza"}),
    "cam_02": ("Metro Transit Hub - East Concourse", {"lat": 12.9780, "lng": 77.6005, "label": "Transit Hub"}),
    "cam_03": ("Stadium Gate 4 - Entry Plaza", {"lat": 12.9698, "lng": 77.5890, "label": "Stadium Gate 4"}),
    "cam_04": ("Financial District - Main Arcade", {"lat": 12.9752, "lng": 77.5912, "label": "Financial District"}),
}


def main() -> None:
    parser = argparse.ArgumentParser(description="Post demo incidents to the local SentinelAI API")
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--interval", type=float, default=15)
    args = parser.parse_args()
    while True:
        camera_id = random.choice(list(CAMERAS))
        camera_name, location = CAMERAS[camera_id]
        incident_type = random.choice(TYPES)
        payload = {
            "event_id": f"evt_{uuid.uuid4().hex}",
            "camera_id": camera_id, "camera_name": camera_name, "location": location,
            "type": incident_type, "confidence": round(random.uniform(0.72, 0.97), 2),
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "snapshot_url": f"/media/snapshots/{camera_id}_{incident_type}.jpg",
            "clip_url": f"/media/clips/{camera_id}_{incident_type}.mp4",
            "notes": "Generated by the offline fake AI worker.",
            "verification": {"window_seconds": 2.5, "frames_confirmed": 36, "frames_required": 25},
        }
        try:
            token = os.getenv("INTERNAL_INGEST_TOKEN")
            headers = {"X-Internal-Token": token} if token else {}
            response = requests.post(f"{args.base_url}/api/internal/incidents", json=payload, headers=headers, timeout=5)
            response.raise_for_status()
            print(f"Posted {response.json()['id']} ({incident_type})")
        except requests.RequestException as error:
            print(f"API unavailable: {error}")
        time.sleep(args.interval)


if __name__ == "__main__":
    main()
